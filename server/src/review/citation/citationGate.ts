import { VaultDb, ClauseRecord, FactRecord } from '../../db/vaultDb.js';
import { FindingDraft } from '../checks/terminology.js';
import { LlmFinding } from '../llm/client.js';

export interface CitationGateResult {
  verifiedFindings: FindingDraft[];
  droppedFindings: Array<{
    rawFinding: LlmFinding;
    reason: string;
  }>;
}

/**
 * Normalizes string whitespace for robust verbatim comparison.
 */
export function normalizeWhitespace(s: string): string {
  return s
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/\s+/g, ' ')
    .replace(/['’]/g, "'")
    .replace(/["“”]/g, '"')
    .trim()
    .toLowerCase();
}

/**
 * The Citation Gate:
 * Enforces the core governance tenet: "No source, no flag."
 * Drops any finding whose cited quote does not exist verbatim in the source clause or fact.
 */
export function enforceCitationGate(
  clientId: string,
  draftText: string,
  rawFindings: LlmFinding[],
  clauses: ClauseRecord[],
  facts: FactRecord[],
  vault?: VaultDb
): CitationGateResult {
  const verifiedFindings: FindingDraft[] = [];
  const droppedFindings: CitationGateResult['droppedFindings'] = [];

  for (const raw of rawFindings) {
    // 1. Look up cited clause or fact
    const citedClause = clauses.find(c => c.id === raw.clause_id);
    const citedFact = facts.find(f => f.id === raw.clause_id);

    const sourceTextAvailable = citedClause ? citedClause.text : citedFact ? citedFact.value : null;

    if (!sourceTextAvailable) {
      const reason = `Cited clause/fact '${raw.clause_id}' does not exist in client vault.`;
      droppedFindings.push({ rawFinding: raw, reason });
      if (vault) {
        vault.logAudit(clientId, 'citation_gate', 'uncited_dropped', raw.clause_id, {
          reason,
          finding: raw
        });
      }
      continue;
    }

    // 2. Check verbatim quotation existence (after whitespace normalization)
    const normSource = normalizeWhitespace(sourceTextAvailable);
    const normQuote = normalizeWhitespace(raw.quote_from_source);

    if (!normQuote || normQuote.length < 5 || !normSource.includes(normQuote)) {
      const reason = `Quote '${raw.quote_from_source}' was not found verbatim in clause ${raw.clause_id}.`;
      droppedFindings.push({ rawFinding: raw, reason });
      if (vault) {
        vault.logAudit(clientId, 'citation_gate', 'uncited_dropped', raw.clause_id, {
          reason,
          finding: raw
        });
      }
      continue;
    }

    // 3. Locate span offsets in the draft text
    let spanStart = draftText.indexOf(raw.span);
    let spanEnd = spanStart !== -1 ? spanStart + raw.span.length : 0;

    // Fallback if span has slight punctuation mismatch
    if (spanStart === -1) {
      const normDraft = normalizeWhitespace(draftText);
      const normSpan = normalizeWhitespace(raw.span);
      const idx = normDraft.indexOf(normSpan);
      spanStart = Math.max(0, idx);
      spanEnd = Math.min(draftText.length, spanStart + raw.span.length);
    }

    verifiedFindings.push({
      id: `f_ai_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      type: raw.issue.toLowerCase().includes('tone') ? 'tone' : 'messaging',
      severity: 'high',
      span_start: Math.max(0, spanStart),
      span_end: Math.max(spanStart + 1, spanEnd),
      span_text: raw.span,
      source_type: 'ai',
      source_id: raw.clause_id,
      source_text: raw.quote_from_source,
      model_name: 'groq/llama-3.3-70b-versatile',
      explanation: raw.explanation,
      suggested_fix: undefined // suggested fix is generated by Intent Lock in Phase 6
    });
  }

  return { verifiedFindings, droppedFindings };
}
